export const SeoStageOverview: React.FC = () => {
  const location = useLocation();
  const navigate = useNavigate();

  const cleanPath =
    location.pathname === '/' ? '/' : `/${location.pathname.split('/').filter(Boolean)[0] || ''}`;
  const routeMeta = SEO_ROUTES[cleanPath] || SEO_ROUTES['/'];

  useEffect(() => {
    if (typeof document === 'undefined') return;
    document.title = routeMeta.title;

    const descMeta = document.querySelector('meta[name="description"]');
    if (descMeta) {
      descMeta.setAttribute('content', routeMeta.description);
    }

    const canonicalLink = document.querySelector('link[rel="canonical"]');
    const canonicalUrl = `${SITE_URL}${routeMeta.path === '/' ? '/' : routeMeta.path}`;
    if (canonicalLink) {
      canonicalLink.setAttribute('href', canonicalUrl);
    }
  }, [routeMeta]);

  const handleLinkClick = (e: React.MouseEvent<HTMLAnchorElement>, targetPath: string) => {
    if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey || e.button !== 0) {
      return;
    }
    e.preventDefault();
    const wsId = getWorkspaceId();
    const target = wsId && targetPath !== '/' ? `${targetPath}?w=${wsId}` : targetPath;
    navigate(target);
  };

  return (
    <section
      aria-label="OSCAL Stage Reference & Lifecycle Documentation"
      style={{
        marginTop: '36px',
        padding: '24px 28px',
        background: 'var(--color-surface)',
        border: '1px solid var(--color-border)',
        borderRadius: 'var(--radius-lg)',
        color: 'var(--color-text)',
        lineHeight: 1.6,
      }}
    >
      <div style={{ borderBottom: '1px solid var(--color-border-subtle)', paddingBottom: '14px', marginBottom: '16px' }}>
        <h2 style={{ fontSize: '16px', fontWeight: 700, margin: '0 0 6px 0', color: 'var(--color-text)' }}>
          {routeMeta.heading}
        </h2>
        <p style={{ fontSize: '13.5px', color: 'var(--color-text-muted)', margin: 0 }}>
          {routeMeta.summary}
        </p>
      </div>

      <div style={{ marginBottom: '20px' }}>
        <h3 style={{ fontSize: '13px', fontWeight: 600, textTransform: 'uppercase', letterSpacing: '0.5px', color: 'var(--color-text-muted)', margin: '0 0 10px 0' }}>
          Key Capabilities &amp; NIST OSCAL Standards
        </h3>
        <ul style={{ margin: 0, paddingLeft: '20px', fontSize: '13px', color: 'var(--color-text-muted)', display: 'grid', gap: '6px' }}>
          {routeMeta.highlights.map((item, idx) => (
            <li key={idx}>{item}</li>
          ))}
        </ul>
      </div>

      <nav
        aria-label="OSCAL Lifecycle Stage Directory"
        style={{
          background: 'var(--color-surface-2)',
          border: '1px solid var(--color-border-subtle)',
          borderRadius: 'var(--radius-md)',
          padding: '14px 16px',
        }}
      >
        <div style={{ fontSize: '12px', fontWeight: 600, color: 'var(--color-text-muted)', marginBottom: '10px' }}>
          OSCAL Compliance Lifecycle Modules:
        </div>
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: '8px' }}>
          {STAGE_LINKS.map((link) => (
            <a
              key={link.path}
              href={link.path}
              onClick={(e) => handleLinkClick(e, link.path)}
              style={{
                display: 'inline-block',
                padding: '5px 10px',
                fontSize: '12px',
                fontWeight: cleanPath === link.path ? 600 : 500,
                background: 'var(--color-surface)',
                border: `1px solid ${cleanPath === link.path ? 'var(--color-accent)' : 'var(--color-border)'}`,
                borderRadius: '6px',
                color: cleanPath === link.path ? 'var(--color-accent)' : 'var(--color-text)',
                textDecoration: 'none',
              }}
            >
              {link.label}
            </a>
          ))}
        </div>
        <div style={{ marginTop: '12px', paddingTop: '10px', borderTop: '1px solid var(--color-border-subtle)', fontSize: '12px', color: 'var(--color-text-muted)', display: 'flex', justifyContent: 'space-between', flexWrap: 'wrap', gap: '8px' }}>
          <span>Reposol — Open-Source NIST OSCAL Viewer &amp; Editor (Apache 2.0)</span>
          <a
            href="https://github.com/philippkatsch/security-management-OSCAL"
            target="_blank"
            rel="noopener noreferrer"
            style={{ color: 'var(--color-accent)', textDecoration: 'none', fontWeight: 500 }}
          >
            GitHub Repository: philippkatsch/security-management-OSCAL ↗
          </a>
        </div>
      </nav>
    </section>
  );
};
